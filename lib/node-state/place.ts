import path from 'node:path'
import { nodePlace } from '@/lib/hosting/place.mjs'

const ROOT = process.cwd()

/** Где живёт узел. `unknown` остаётся в типе ради старых слов островка — определение его больше не возвращает. */
export type PlaceKind = 'home' | 'server' | 'unknown'

export type Place = {
  kind: PlaceKind
  /** installed — записала установка; migrated — записал первый запуск после 741; moved — метка запуска сервера; measured — замер */
  source: 'installed' | 'migrated' | 'moved' | 'measured' | 'unknown'
  changedAt: string | null
  detail?: string
  /** замер видит иначе (его объяснение) — запись всё равно главнее */
  mismatch?: string
  /** запись написана на другой машине — узел идёт по замеру */
  foreign?: true
}

export function readPlace(): Place {
  return nodePlace(path.resolve(ROOT)) as Place
}
