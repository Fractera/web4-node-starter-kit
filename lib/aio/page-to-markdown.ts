import type { PageItem, FaqPair } from '@/lib/content/sections/types'
import { resolveMarkdownLinks } from '@/lib/content/sections/links'
import { termPlain } from '@/lib/content/sections/term'

// Секции страницы → markdown (шаг 505, AIO).
//
// ЗАЧЕМ. Публичная страница существует в двух видах: HTML для человека и markdown
// для машины. Второй нужен затем, что модель, пришедшая за содержимым сайта,
// разбирает разметку страницы вместе с меню, подвалом, баннером согласия и
// скриптами — и половину контекста тратит на то, что к содержимому отношения не
// имеет. Markdown отдаёт ровно текст.
//
// 🔒 ИСТОЧНИК ОДИН. Обе формы собираются из ОДНИХ И ТЕХ ЖЕ секций, поэтому
// разойтись не могут: отредактировал текст — изменились обе. Отдельный файл с
// «версией для ИИ» разошёлся бы с сайтом на первой же правке, и никто бы этого
// не заметил, потому что в браузере его никто не открывает.
//
// Инлайновая разметка (`**жирный**`, `[метка](адрес)`) в наших секциях УЖЕ
// markdown — переносится как есть.
//
// 🔒 КРОМЕ ОДНОЙ ФОРМЫ, И ИМЕННО НА НЕЙ ЭТО ОБЕЩАНИЕ ЛОМАЛОСЬ (2026-08-17).
// Ссылка на корень пишется `[%SITE%](/en)` — это не markdown, а соглашение
// проекта, которое раскрывает рендерер: подпись становится названием сайта.
// Машинная версия «переносила как есть» и отдавала дословный `%SITE%` с
// относительным адресом, который вне сайта не разрешается ни во что. То есть
// ровно та ссылка, ради которой правило и придумано, до машины не доезжала.
// Раскрывает её теперь `resolveMarkdownLinks` — там же, где живут все прочие
// решения о ссылках, чтобы обе формы страницы не разошлись снова.

function lines(item: PageItem): string[] {
  switch (item.kind) {
    case 'h2':
      return [`## ${item.text}`]
    case 'h3':
      return [`### ${item.text}`]
    // Четвёртый и пятый уровни (шаг 30-1). Модель обязана видеть ТУ ЖЕ глубину,
    // что человек: markdown-версия страницы существует ради структуры, и
    // уплощённые здесь заголовки превратили бы дерево документа в плоский список.
    case 'h4':
      return [`#### ${item.text}`]
    case 'h5':
      return [`##### ${item.text}`]
    case 'p':
      return [item.text]
    case 'note':
      return [item.text]
    case 'quote':
      // Цитата вместе с источником: без него утверждение теряет автора, а это
      // ровно то, ради чего цитату и приводят.
      // `lead` — первая строка самой цитаты, поэтому и в тексте она остаётся
      // ВНУТРИ цитаты, жирной строкой: вынести её наружу заголовком значило бы
      // объявить машинному читателю раздел, которого на странице нет.
      return [
        ...(item.lead ? [`> **${item.lead}**`, `>`] : []),
        `> ${item.text}`,
        ...(item.cite ? [`>`, `> — ${item.cite}`] : []),
      ]
    case 'founder':
      return [`> ${item.text}`]
    case 'list':
      return item.items.map(i => `- ${i}`)
    case 'olist':
      return item.items.map((i, n) => `${n + 1}. ${i}`)
    case 'code':
      return ['```', item.text, '```']
    // Подпись у кнопки необязательна: там, где заголовок раздела уже сказал то
    // же самое, её убрали. Без подписи остаётся сама ссылка.
    case 'cta':
      return [item.text ? `${item.text} — [${item.label}](${item.href})` : `[${item.label}](${item.href})`]
    case 'callout':
      return [`**${item.title}** ${item.text}`]
    case 'docref':
      return [`**${item.title}** — ${item.summary}: [${item.label ?? 'документ'}](${item.href})`]
    case 'figure':
      // Изображение описывается СЛОВАМИ. Модель картинку не увидит, а `alt` и
      // подпись — это то, ради чего её поставили.
      return [`![${item.alt}](${item.src})`, ...(item.caption ? [`*${item.caption}*`] : [])]
    case 'table': {
      const head = `| ${item.headers.join(' | ')} |`
      const sep = `| ${item.headers.map(() => '---').join(' | ')} |`
      const body = item.rows.map(r => `| ${r.join(' | ')} |`)
      return [...(item.caption ? [item.caption, ''] : []), head, sep, ...body]
    }
    // Первый экран лендинга. Иллюстрация опускается намеренно: она из слота
    // настроек, у каждого проекта своя, и её адрес машинному читателю не говорит
    // ничего. А вот заголовок с описанием — самый весомый текст страницы, и
    // потерять его здесь значило бы отдать модели пустую главную.
    case 'heroSplit':
      return [`## ${item.title}`, '', item.description]
    // Завершающая секция. Восемьдесят два названия языков машинному читателю не
    // нужны — он их и так знает; смысл секции целиком в её заголовке.
    case 'languageMarquee':
      return [`## ${item.title}`, ...(item.note ? ['', item.note] : [])]
    // Ряд мер. Число без слова при нём — не утверждение, а цифра, поэтому пара
    // едет вместе одной строкой списка.
    case 'metrics':
      return item.items.map(m => `- **${m.value}** — ${m.label}`)
    // «Как это работает». Очерёдность здесь — само содержание, и нумерованный
    // список передаёт её точнее любой прозы. Зажигание опускается намеренно: это
    // подача, а машинному читателю нужен порядок, а не подсветка.
    case 'flow':
      return [
        `## ${item.title}`,
        ...(item.note ? ['', item.note] : []),
        '',
        ...item.steps.map((s, n) => `${n + 1}. **${s.title}** — ${s.text}`),
      ]
    // Раздел карточками. Ярлык рубрики опускается: машинному читателю он не
    // говорит ничего, чего не говорит заголовок.
    case 'cards':
      return [
        `## ${item.title}`,
        ...(item.note ? ['', item.note] : []),
        '',
        ...item.children.flatMap(child => [...lines(child), '']),
      ]
    // Ячейка — контейнер: раскрываем содержимое, как `columns` и `group`.
    case 'card':
      return item.children.flatMap(child => [...lines(child), ''])
    // Крупное утверждение. Для машины это обычная цитата: разрядка и градиент —
    // способ показать её человеку, а не часть смысла.
    case 'statement':
      return [`> ${item.text}`]
    // Счета, которых не будет. Зачёркивание — знак на экране; словами то же
    // самое говорит сама фраза, поэтому имя поставщика просто стоит при ней, а
    // ярлык — в скобках: «Neon» без пояснения машинному читателю говорит мало.
    case 'noBill':
      return [
        `## ${item.heading}`,
        ...(item.note ? ['', item.note] : []),
        '',
        ...item.items.map(i => `- ${i.text} ${i.vendor} (${i.badge.label})`),
        '',
        `### ${item.title}`,
        '',
        item.text,
      ]
    case 'columns':
    case 'group':
      // Контейнер — раскладка, а не содержимое: разворачиваем детей.
      return item.children.flatMap(child => [...lines(child), ''])
    // Рабочий экран.
    //
    // 🔒 МЕНЮ И ВКЛАДКИ МАШИНЕ НЕ ОТДАЮТСЯ, И ЭТО НЕ ПОТЕРЯ. Это НАВИГАЦИЯ — она
    // сообщает, куда можно уйти с этого экрана, а не что на нём написано.
    // Модель, прочитав список из восьми пунктов, пересказала бы его как
    // содержание страницы. Заголовок, описание и карточки — содержание, они
    // едут; карточки при этом сохраняют свой тон словом, потому что «состояние
    // системы» и «цена решения» — разные утверждения, и цвет их различает только
    // на экране.
    case 'workspace':
      return [
        `## ${item.title}`,
        ...(item.lead ? ['', item.lead] : []),
        ...(item.notes ?? []).flatMap(n => ['', `**${n.title}** (${n.tone}) — ${n.text}`]),
        '',
        ...item.children.flatMap(child => [...lines(child), '']),
      ]
    default:
      return []
  }
}

/**
 * 🔒 `siteName` ОБЯЗАТЕЛЕН, И ЭТО ИСПРАВЛЕНИЕ, А НЕ УДОБСТВО (2026-08-17).
 *
 * Комментарий вверху файла обещал, что инлайновая разметка «уже markdown и
 * переносится как есть». Для жирного и обычных ссылок это правда, для одной
 * формы — нет: `[%SITE%](/en)` раскрывает рендерер, и без него машина получала
 * дословный `%SITE%` и относительный адрес, который вне сайта не разрешается ни
 * во что. Параметр сделан ОБЯЗАТЕЛЬНЫМ намеренно: с умолчанием следующая
 * поверхность молча забыла бы его передать, и дефект вернулся бы туда же.
 */
export function pageToMarkdown(body: PageItem[], siteName: string): string {
  // 599-1: подсказка к слову — не markdown; машина получает только форму слова (`termPlain`).
  return resolveMarkdownLinks(
    termPlain(
      body
        .flatMap(b => [...lines(b), ''])
        .join('\n')
        .replace(/\n{3,}/g, '\n\n')
        .trim(),
    ),
    siteName,
  )
}

/**
 * Вопросы и ответы отдельным разделом.
 *
 * Форма пары — `{ q, a }` из общего каталога секций (`FaqPair`), а не
 * `{ question, answer }`: типы поймали это на сборке, и подгонять надо код под
 * каталог, а не наоборот — каталог читают ещё и разметка страницы, и JSON-LD.
 */
export function faqToMarkdown(faq?: FaqPair[]): string {
  if (!faq?.length) return ''
  return ['## FAQ', '', ...faq.flatMap(f => [`### ${f.q}`, '', f.a, ''])].join('\n').trim()
}
