/** Домены, которые Cloudflare раздаёт быстрым туннелям. Ровно они, без поддоменов третьих лиц. */
// 737-2: и голый IP выделенного сервера до его домена — тот же закон «только чтение» (`isBareIpHostname`, единое место знания).
import { TEMPORARY_SUFFIXES, isBareIpHostname } from "@/components/shell/temporary-host"
import { placeKind } from "@/lib/hosting/place.mjs"
import { requestHostname, temporaryFor } from "@/lib/auth/request-signs.mjs"

/**
 * Принадлежит ли ИМЯ ХОСТА быстрому туннелю или голому IP. Голое имя, без места узла: место решает `isTemporaryPublicAddress`.
 *
 * 🛑 СВЕРЯЕТСЯ ТОЛЬКО ХВОСТ ИМЕНИ, А НЕ АДРЕС ЦЕЛИКОМ. Имя быстрого туннеля —
 * четыре случайных слова, оно меняется при каждом перезапуске: правило, знающее
 * адрес целиком, перестало бы работать в тот же день, и незаметно.
 */
export function isTemporaryHostname(hostname: string): boolean {
  const bare = (hostname ?? "").trim().toLowerCase().replace(/:\d+$/, "")
  return TEMPORARY_SUFFIXES.some((suffix) => bare.endsWith(suffix)) || isBareIpHostname(hostname)
}

/**
 * Пришёл ли запрос на ВРЕМЕННЫЙ публичный адрес узла — на компьютере человека; на сервере никогда (741-3).
 *
 * Запроса нет (серверный вызов внутри процесса) — `false`: молчаливая выдача
 * прав тому, чьё происхождение неизвестно, и есть тот класс дефекта, которым
 * оплачен `auth-bypass.ts`.
 */
export function isTemporaryPublicAddress(req?: NextRequest): boolean {
  if (!req) return false
  return temporaryFor(placeKind(process.cwd()), requestHostname((name: string) => req.headers.get(name)), isTemporaryHostname)
}
